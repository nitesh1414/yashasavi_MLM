<?php
/** Safe, optional rank artwork. Images are decoded and re-encoded as PNG. */

function rank_icon_storage_available()
{
    return (int)q_val("SELECT COUNT(*) FROM information_schema.COLUMNS
                       WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='ranks' AND COLUMN_NAME='icon_image'") === 1;
}

function rank_icon_safe_path($path)
{
    return is_string($path) && (bool)preg_match('~^rank-icons/[a-f0-9]{32}\.png$~D', $path);
}

function rank_icon_url($path)
{
    if (!rank_icon_safe_path($path)) { return null; }
    $file = dirname(__DIR__) . '/uploads/' . $path;
    clearstatcache(true, $file);
    return is_file($file) && !is_link($file) ? upload_url($path) : null;
}

/**
 * Accept only an actual HTTP upload. The original name and bytes are never
 * served: decoding and encoding removes appended scripts/metadata, and creates
 * a random PNG name. Return null when no file was supplied.
 */
function rank_icon_upload($field)
{
    if (!isset($_FILES[$field])) { return null; }
    $file = $_FILES[$field];
    if (!is_array($file) || !isset($file['error']) || is_array($file['error'])) {
        throw new RuntimeException('Invalid rank image upload.');
    }
    if ((int)$file['error'] === UPLOAD_ERR_NO_FILE) { return null; }
    if ((int)$file['error'] !== UPLOAD_ERR_OK) { throw new RuntimeException('Rank image upload failed. Check the server upload size limit.'); }
    if (!isset($file['name'], $file['tmp_name']) || !is_string($file['name']) || !is_string($file['tmp_name'])
        || !is_uploaded_file($file['tmp_name'])) {
        throw new RuntimeException('Rank image must be an HTTP upload.');
    }
    $limit = min((int)MAX_UPLOAD_MB * 1024 * 1024, 5 * 1024 * 1024);
    $size = @filesize($file['tmp_name']);
    if (!$size || $size > $limit) { throw new RuntimeException('Rank image must be non-empty and no larger than ' . round($limit / 1048576, 1) . ' MB.'); }
    $ext = strtolower(pathinfo($file['name'], PATHINFO_EXTENSION));
    $allowed = ['jpg'=>'image/jpeg', 'jpeg'=>'image/jpeg', 'png'=>'image/png', 'gif'=>'image/gif', 'webp'=>'image/webp'];
    $info = @getimagesize($file['tmp_name']);
    if (!isset($allowed[$ext]) || !$info || ($info['mime'] ?? '') !== $allowed[$ext]
        || $info[0] < 1 || $info[1] < 1 || $info[0] > 2048 || $info[1] > 2048
        || $info[0] * $info[1] > 4194304) {
        throw new RuntimeException('Use a valid JPG, PNG, GIF or WebP image, at most 2048 × 2048 pixels.');
    }
    if (!function_exists('imagecreatefromstring') || !function_exists('imagepng')) {
        throw new RuntimeException('Rank image uploads require the PHP GD extension.');
    }
    $bytes = @file_get_contents($file['tmp_name']);
    $image = $bytes === false ? false : @imagecreatefromstring($bytes);
    if (!$image) { throw new RuntimeException('The rank image could not be decoded.'); }
    $target = null;
    $created = false;
    try {
        $uploads = dirname(__DIR__) . '/uploads';
        $dir = $uploads . '/rank-icons';
        clearstatcache(true, $dir);
        if (is_link($dir) || (!is_dir($dir) && !@mkdir($dir, 0755, true) && !is_dir($dir))
            || realpath($dir) !== realpath($uploads) . DIRECTORY_SEPARATOR . 'rank-icons') {
            throw new RuntimeException('The rank icon folder is unavailable. Check its permissions.');
        }
        $path = 'rank-icons/' . bin2hex(random_bytes(16)) . '.png';
        $target = $uploads . '/' . $path;
        $out = @fopen($target, 'x');
        if (!$out) { throw new RuntimeException('Could not save the rank image.'); }
        $created = true;
        imagealphablending($image, false);
        imagesavealpha($image, true);
        try { $written = @imagepng($image, $out); } finally { fclose($out); }
        if (!$written || !is_file($target) || filesize($target) < 1) {
            throw new RuntimeException('Could not save the rank image.');
        }
        @chmod($target, 0644);
        return $path;
    } catch (Throwable $e) {
        if ($created && $target && is_file($target)) { @unlink($target); }
        throw $e;
    } finally {
        imagedestroy($image);
    }
}

/** Delete only paths generated by this feature, and only when no rank uses it. */
function rank_icon_delete_unreferenced($path)
{
    if (!rank_icon_safe_path($path) || !rank_icon_storage_available()) { return; }
    if ((int)q_val('SELECT COUNT(*) FROM ranks WHERE icon_image=?', [$path]) > 0) { return; }
    $uploads = dirname(__DIR__) . '/uploads';
    $dir = $uploads . '/rank-icons';
    $file = $uploads . '/' . $path;
    clearstatcache(true, $dir);
    clearstatcache(true, $file);
    if (!is_link($dir) && realpath($dir) === realpath($uploads) . DIRECTORY_SEPARATOR . 'rank-icons'
        && is_file($file) && !is_link($file) && !@unlink($file)) {
        error_log('Could not delete unreferenced rank icon.');
    }
}
